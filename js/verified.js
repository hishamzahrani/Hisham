/** توحيد النص للمطابقة: حذف التشكيل والتطويل وتوحيد الهمزات */
function normAr(s) {
  return String(s || "")
    .replace(/[ً-ٰٟـ]/g, "")
    .replace(/[أإآٱ]/g, "ا").replace(/[ؤ]/g, "و").replace(/[ئ]/g, "ي").replace(/ء/g, "")
    .replace(/[«»﴾﴿]/g, "");
}

